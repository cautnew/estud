<?php

namespace App\Http\Controllers\Admin;

use App\Actions\ExamNotices\ImportExamNoticeFromJson;
use App\Http\Controllers\Controller;
use App\Http\Requests\ExamNoticeImportRequest;
use Illuminate\Http\RedirectResponse;
use Inertia\Inertia;
use Inertia\Response;

class ExamNoticeImportController extends Controller
{
    /**
     * Show the import page with the AI prompt template and the paste form.
     */
    public function create(): Response
    {
        return Inertia::render('admin/exam-notices/import');
    }

    /**
     * Import an exam notice from a JSON payload, typically generated by an
     * AI chat from the official edital text.
     */
    public function store(ExamNoticeImportRequest $request, ImportExamNoticeFromJson $importExamNoticeFromJson): RedirectResponse
    {
        $examNotice = $importExamNoticeFromJson->handle($request->validated('data'), $request->user());

        Inertia::flash('toast', ['type' => 'success', 'message' => __('Edital importado.')]);

        return to_route('admin.exam-notices.show', $examNotice);
    }
}
